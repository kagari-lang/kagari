// Kagari's source grammar, not its static type/visibility rules.
const PREC = { closure: -2, range: -1, or: 1, and: 2, equality: 3,
  compare: 4, bitOr: 5, bitXor: 6, bitAnd: 7, shift: 8, add: 9,
  multiply: 10, cast: 11, unary: 12, call: 13 };
const commaSep1 = rule => seq(rule, repeat(seq(',', rule)), optional(','));
const commaSep = rule => optional(commaSep1(rule));
const binaryOperators = [
  ['||', PREC.or], ['&&', PREC.and],
  ...['==', '!=', '===', '!=='].map(op => [op, PREC.equality]),
  ...['<', '<=', '>', '>='].map(op => [op, PREC.compare]),
  ['|', PREC.bitOr], ['^', PREC.bitXor], ['&', PREC.bitAnd],
  ['<<', PREC.shift], ['>>', PREC.shift],
  ...['+', '-'].map(op => [op, PREC.add]),
  ...['*', '/', '%'].map(op => [op, PREC.multiply]),
];
function binary($, expr) {
  return choice(...binaryOperators.map(([op, precedence]) => prec.left(precedence,
    seq(field('left', expr), field('operator', op), field('right', expr)))));
}
function range($, expr) {
  // Before a control-flow body, reduce an open range instead of eating its brace.
  return prec.left(PREC.range, choice(
    seq(optional(field('start', expr)), '..', optional(field('end', expr))),
    seq(optional(field('start', expr)), '..=', field('end', expr))));
}
function postfix($, expr) {
  return choice(
    $.call_expression, $.field_expression, $.index_expression,
    $.propagation_expression, $.await_expression);
}
module.exports = grammar({
  name: 'kagari',
  word: $ => $.identifier,
  reserved: {
    global: $ => ['as', 'async', 'await', 'break', 'const', 'continue', 'crate', 'else',
      'enum', 'false', 'fn', 'for', 'trait', 'if', 'impl', 'in', 'loop', 'match',
      'mod', 'pub', 'return', 'self', 'static', 'struct', 'super', 'true', 'use', 'val',
      'var', 'type', 'where', 'while'],
  },
  inline: $ => [$.type_identifier],
  extras: $ => [/[\u0009-\u000d \u0085\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000]/,
    $.line_comment, $.doc_line_comment, $.block_comment,
    $.doc_block_comment, $.unterminated_block_comment],
  externals: $ => [$.block_comment, $.doc_block_comment, $.unterminated_block_comment,
    $.string_content, $._string_end, $.unterminated_string_end,
    $._scanner_recovery, $._char_boundary, $.raw_string_literal, $.unterminated_raw_string,
    $._hole_boundary, $._hole_name, $.raw_byte_string_literal, $.unterminated_raw_byte_string,
    $.byte_string_content],
  conflicts: $ => [
    [$.path],
    [$._atom, $.generic_path, $.struct_expression],
    [$._atom, $.generic_path],
    [$._atom, $.struct_expression],
    [$._type, $.generic_type],
    [$._atom, $._bare_block_statement],

  ],
  rules: {
    source_file: $ => repeat($._item),
    _item: $ => choice($.function_item, $.const_item, $.static_item, $.struct_item, $.enum_item,
      $.trait_item, $.impl_item, $.module_item, $.use_item, $.type_alias_item),
    visibility: $ => seq('pub', optional(seq('(', choice('super', 'crate'), ')'))),
    attribute: $ => seq('#', '[', field('name', $.path), optional(choice(
      seq('=', $._attribute_value), $.attribute_arguments)), ']'),
    attribute_arguments: $ => seq('(', commaSep($.attribute_argument), ')'),
    attribute_argument: $ => seq(optional(seq(field('name', $.identifier), '=')), $._attribute_value),
    _attribute_value: $ => choice($._scalar_literal, $.path, $.attribute_array),
    attribute_array: $ => seq('[', commaSep($.attribute_argument), ']'),
    module_item: $ => seq(repeat($.attribute), optional($.visibility), 'mod',
      field('name', $.identifier), choice(';', field('body', $.module_body))),
    module_body: $ => seq('{', repeat($._item), '}'),
    use_item: $ => seq(repeat($.attribute), optional($.visibility), 'use', $.use_tree, ';'),
    use_tree: $ => choice(seq($.path, optional(choice(seq('as', field('alias', $.identifier)),
      seq('::', choice('*', $.use_group))))), $.use_group),
    use_group: $ => seq('{', commaSep($.use_tree), '}'),
    function_item: $ => seq(repeat($.attribute), optional($.visibility), optional('async'),
      'fn', field('name', $.identifier), optional($.generic_parameters),
      field('parameters', $.parameters), optional($.return_type), optional($.where_clause),
      field('body', $.block)),
    parameters: $ => seq('(', commaSep($.parameter), ')'),
    parameter: $ => seq(field('name', $.identifier), ':', field('type', $._type)),
    return_type: $ => seq('->', $._type),
    const_item: $ => seq(repeat($.attribute), optional($.visibility), 'const',
      field('name', $.identifier), optional($.type_annotation), '=', field('value', $._expression), ';'),
    static_item: $ => seq(repeat($.attribute), optional($.visibility), 'static', choice('val', 'var'),
      field('name', $.identifier), ':', field('type', $._type), '=', field('value', $._expression), ';'),
    type_alias_item: $ => seq(repeat($.attribute), optional($.visibility), 'type',
      field('name', $.type_identifier), optional($.generic_parameters),
      choice(seq($.where_clause, '=', field('type', $._type)),
        seq('=', field('type', $._type), optional($.where_clause))), ';'),
    struct_item: $ => seq(repeat($.attribute), optional($.visibility), 'struct',
      field('name', $.type_identifier), optional($.generic_parameters),
      field('body', $.field_declarations)),
    field_declarations: $ => seq('{', commaSep($.field_declaration), '}'),
    field_declaration: $ => seq(repeat($.attribute), optional($.visibility), choice('val', 'var'),
      field('name', $.identifier), ':', field('type', $._type)),
    enum_item: $ => seq(repeat($.attribute), optional($.visibility), 'enum',
      field('name', $.type_identifier), optional($.generic_parameters),
      '{', commaSep($.enum_variant), '}'),
    enum_variant: $ => seq(field('name', $.identifier), optional(seq('(', commaSep($._type), ')'))),
    trait_item: $ => seq(repeat($.attribute), optional($.visibility), 'trait',
      field('name', $.type_identifier), optional($.generic_parameters), optional($.type_bounds),
      '{', repeat(choice($.method_item, $.associated_type, $.associated_const)), '}'),
    impl_item: $ => seq(repeat($.attribute), 'impl', optional($.generic_parameters),
      choice(seq(field('trait', $.trait_reference), 'for', field('type', $._type)),
        field('type', $._type)), optional($.where_clause), '{',
      repeat(choice($.method_item, $.associated_type, $.associated_const)), '}'),
    method_item: $ => seq(repeat($.attribute), optional($.visibility), optional('async'), 'fn',
      field('name', $.identifier), optional($.generic_parameters), field('parameters', $.method_parameters),
      optional($.return_type), optional($.where_clause), choice(';', field('body', $.block))),
    method_parameters: $ => seq('(', commaSep(choice($.receiver_parameter, $.parameter)), ')'),
    receiver_parameter: $ => 'self',
    associated_type: $ => seq(repeat($.attribute), 'type', field('name', $.type_identifier),
      optional($.generic_parameters), optional($.type_bounds), optional(seq('=', $._type)),
      optional($.where_clause), ';'),
    associated_const: $ => seq(repeat($.attribute), 'const', field('name', $.identifier), ':',
      field('type', $._type), optional(seq('=', field('value', $._expression))), ';'),
    generic_parameters: $ => seq('<', commaSep1($.type_parameter), '>'),
    type_parameter: $ => seq(field('name', $.type_identifier), optional($.type_bounds)),
    type_bounds: $ => seq(':', $.trait_reference, repeat(seq('+', $.trait_reference))),
    trait_reference: $ => seq($.type_path, optional(choice($.generic_arguments, $.callable_arguments))),
    callable_arguments: $ => seq('(', commaSep($._type), ')', optional($.return_type)),
    where_clause: $ => seq('where', commaSep1($.where_predicate)),
    where_predicate: $ => seq($._type, $.type_bounds),
    type_annotation: $ => seq(':', $._type),
    _type: $ => choice($.type_path, $.generic_type, $.qualified_type, $.array_type,
      $.tuple_type, $.parenthesized_type, $.function_type, $.never_type),
    type_identifier: $ => alias($.identifier, $.type_identifier),
    type_path: $ => prec.right(seq(repeat(seq(choice($.identifier, 'crate', 'self', 'super'), '::')),
      choice($.type_identifier, 'self', 'super', 'crate'))),
    generic_type: $ => seq($.type_path, $.generic_arguments),
    generic_arguments: $ => seq('<', commaSep1(choice($._type, $.associated_type_binding)), '>'),
    associated_type_binding: $ => seq(field('name', $.type_identifier), '=', field('type', $._type)),
    qualified_type: $ => prec.right(seq('<', $._type, 'as', $.trait_reference, '>', '::',
      field('name', $.type_identifier), optional($.generic_arguments))),
    array_type: $ => seq('[', $._type, ']'),
    tuple_type: $ => seq('(', optional(seq($._type, ',', commaSep($._type))), ')'),
    parenthesized_type: $ => seq('(', $._type, ')'),
    function_type: $ => seq('fn', '(', commaSep($._type), ')', '->', $._type),
    never_type: $ => '!',
    block: $ => seq('{', repeat($._statement), optional(field('tail', $._expression)), '}'),
    _statement: $ => choice($.binding_statement, $.assignment_statement, $.expression_statement,
      $.return_statement, $.break_statement, $.continue_statement, $.while_statement,
      $.for_statement, $.function_item, $._bare_block_statement),
    _bare_block_statement: $ => prec.dynamic(-1, choice($.block, $.if_expression, $.loop_expression)),
    binding_statement: $ => seq(choice('val', 'var'), field('pattern', $._single_pattern),
      optional($.type_annotation), optional(seq('=', field('value', $._expression))), ';'),
    assignment_statement: $ => seq(field('left', $._expression),
      field('operator', choice('=', '+=', '-=', '*=', '/=', '%=', '&=', '|=', '^=', '<<=', '>>=')),
      field('right', $._expression), ';'),
    expression_statement: $ => seq($._expression, ';'),
    return_statement: $ => seq('return', optional($._expression), ';'),
    break_statement: $ => seq('break', optional($._expression), ';'),
    continue_statement: $ => seq('continue', ';'),
    while_statement: $ => seq('while', $._condition, field('body', $.block)),
    for_statement: $ => seq('for', field('pattern', $._pattern), 'in',
      field('value', $._condition_expression), field('body', $.block)),
    _condition: $ => choice($._condition_expression, $.binding_condition),
    binding_condition: $ => seq('val', field('pattern', $._pattern), '=',
      field('value', $._condition_expression)),
    _expression: $ => choice($._non_range_expression, $.range_expression),
    _non_range_expression: $ => choice($._atom, $.struct_expression, $.binary_expression,
      $.unary_expression, $.cast_expression, postfix($)),
    _atom: $ => choice($._literal, $.interpolated_string, $.path, $.generic_path, $.qualified_type,
      $.parenthesized_expression, $.tuple_expression, $.array_expression, $.closure_expression, $.async_block_expression,
      $.if_expression, $.match_expression, $.loop_expression, $.block),
    path: $ => seq(choice($.identifier, 'crate', 'self', 'super'),
      repeat(seq('::', choice($.identifier, 'crate', 'self', 'super')))),
    generic_path: $ => choice(
      seq($.path, $.generic_arguments, '::', field('name', $.identifier)),
      seq($.path, '::', $.generic_arguments)),
    binary_expression: $ => binary($, $._non_range_expression),
    range_expression: $ => range($, $._non_range_expression),
    unary_expression: $ => prec(PREC.unary, seq(field('operator', choice('-', '!')), field('argument', $._non_range_expression))),
    cast_expression: $ => prec.left(PREC.cast, seq(field('value', $._non_range_expression), 'as', field('type', $._type))),
    call_expression: $ => prec(PREC.call, seq(field('function', $._non_range_expression),
      optional(seq('::', $.generic_arguments)), field('arguments', $.arguments))),
    arguments: $ => seq('(', commaSep($._expression), ')'),
    field_expression: $ => prec(PREC.call, seq(field('value', $._non_range_expression), '.', field('field', $.identifier))),
    index_expression: $ => prec(PREC.call, seq(field('value', $._non_range_expression), '[', field('index', $._expression), ']')),
    propagation_expression: $ => prec(PREC.call, seq($._non_range_expression, '?')),
    await_expression: $ => prec(PREC.call, seq($._non_range_expression, '.', 'await')),
    // Reserve a bare path's following brace for a control-flow body. Parentheses,
    // calls, arrays and holes deliberately re-enter unrestricted expression syntax.
    _condition_expression: $ => choice($._condition_non_range_expression,
      alias($._condition_range_expression, $.range_expression)),
    _condition_non_range_expression: $ => choice($._atom,
      alias($._condition_binary_expression, $.binary_expression),
      alias($._condition_unary_expression, $.unary_expression),
      alias($._condition_cast_expression, $.cast_expression),
      alias($._condition_call_expression, $.call_expression),
      alias($._condition_field_expression, $.field_expression),
      alias($._condition_index_expression, $.index_expression),
      alias($._condition_propagation_expression, $.propagation_expression),
      alias($._condition_await_expression, $.await_expression)),
    _condition_binary_expression: $ => binary($, $._condition_non_range_expression),
    _condition_range_expression: $ => range($, $._condition_non_range_expression),
    _condition_unary_expression: $ => prec(PREC.unary, seq(field('operator', choice('-', '!')), field('argument', $._condition_non_range_expression))),
    _condition_cast_expression: $ => prec.left(PREC.cast, seq(field('value', $._condition_non_range_expression), 'as', field('type', $._type))),
    _condition_call_expression: $ => prec(PREC.call, seq(field('function', $._condition_non_range_expression),
      optional(seq('::', $.generic_arguments)), field('arguments', $.arguments))),
    _condition_field_expression: $ => prec(PREC.call, seq(field('value', $._condition_non_range_expression), '.', field('field', $.identifier))),
    _condition_index_expression: $ => prec(PREC.call, seq(field('value', $._condition_non_range_expression), '[', field('index', $._expression), ']')),
    _condition_propagation_expression: $ => prec(PREC.call, seq($._condition_non_range_expression, '?')),
    _condition_await_expression: $ => prec(PREC.call, seq($._condition_non_range_expression, '.', 'await')),
    parenthesized_expression: $ => seq('(', $._expression, ')'),
    tuple_expression: $ => seq('(', optional(seq($._expression, ',', commaSep($._expression))), ')'),
    array_expression: $ => seq('[', optional(choice(commaSep1($._expression),
      seq($._expression, ';', $._expression))), ']'),
    struct_expression: $ => seq(field('type', $.path), optional($.generic_arguments), '{', optional(choice(
      seq($.field_initializer, repeat(seq(',', $.field_initializer)),
        optional(choice(',', seq(',', field('base', $.struct_update_base))))),
      field('base', $.struct_update_base))), '}'),
    field_initializer: $ => seq(field('name', $.identifier), optional(seq(':', field('value', $._expression)))),
    struct_update_base: $ => seq('..', field('value', $._expression)),
    async_block_expression: $ => seq('async', field('body', $.block)),
    closure_expression: $ => prec.right(PREC.closure, seq(optional('async'), $.closure_parameters, field('body', $._expression))),
    closure_parameters: $ => choice('||', seq('|', commaSep($.closure_parameter), '|')),
    closure_parameter: $ => seq(field('name', $.identifier), optional($.type_annotation)),
    if_expression: $ => prec.right(seq('if', field('condition', $._condition),
      field('consequence', $.block), optional(seq('else', field('alternative', choice($.block, $.if_expression)))))),
    loop_expression: $ => seq('loop', field('body', $.block)),
    match_expression: $ => seq('match', field('value', $._condition_expression), '{', commaSep($.match_arm), '}'),
    match_arm: $ => seq(field('pattern', $._pattern), optional($.match_guard), '=>', field('value', $._expression)),
    match_guard: $ => seq('if', $._expression),
    _pattern: $ => choice($._single_pattern, $.or_pattern),
    _single_pattern: $ => choice($._primary_pattern, $.range_pattern),
    _primary_pattern: $ => choice($.wildcard_pattern, $._scalar_literal, $.path, $.generic_path,
      $.tuple_pattern, $.parenthesized_pattern, $.tuple_struct_pattern, $.struct_pattern),
    wildcard_pattern: $ => '_',
    or_pattern: $ => prec.left(1, seq($._pattern, '|', $._pattern)),
    range_pattern: $ => prec(2, seq($._primary_pattern, choice('..', '..='), choice($._scalar_literal, $.path))),
    tuple_pattern: $ => seq('(', optional(seq($._pattern, ',', commaSep($._pattern))), ')'),
    parenthesized_pattern: $ => seq('(', $._pattern, ')'),
    tuple_struct_pattern: $ => seq(choice($.path, $.generic_path), '(', commaSep($._pattern), ')'),
    struct_pattern: $ => seq(field('type', choice($.path, $.generic_path)), '{', optional(choice(
      seq($.field_pattern, repeat(seq(',', $.field_pattern)), optional(seq(',', $.rest_pattern)), optional(',')),
      seq($.rest_pattern, optional(',')))), '}'),
    field_pattern: $ => seq(field('name', $.identifier), optional(seq(':', field('pattern', $._pattern)))),
    rest_pattern: $ => '..',
    // Byte strings construct arrays; only expressions admit them, never scalar metadata or patterns.
    _literal: $ => choice($._scalar_literal, $.byte_string_literal, $.raw_byte_string_literal,
      $.unterminated_raw_byte_string),
    _scalar_literal: $ => choice($.integer_literal, $.float_literal, $.string_literal, $.raw_string_literal,
      $.unterminated_raw_string, $.boolean_literal, $.char_literal, $.byte_char_literal),
    integer_literal: $ => token(seq(choice(/[0-9][0-9_]*/, /0b_*[01][01_]*/,
      /0o_*[0-7][0-7_]*/, /0x_*[0-9a-fA-F][0-9a-fA-F_]*/),
      optional(choice('i8', 'i16', 'i32', 'i64', 'u8', 'u16', 'u32', 'u64')))),
    float_literal: $ => token(choice(
      seq(/[0-9][0-9_]*\.[0-9][0-9_]*/, optional(/[eE][+-]?[0-9][0-9_]*/), optional(choice('f32', 'f64'))),
      seq(/[0-9][0-9_]*[eE][+-]?[0-9][0-9_]*/, optional(choice('f32', 'f64'))),
      seq(/[0-9][0-9_]*/, choice('f32', 'f64')))),
    boolean_literal: $ => choice('true', 'false'),
    // Only lexical shape lives here; kagari-source owns decoded scalar validation.
    // Immediate tokens reject internal trivia; the never-emitted boundary marker
    // also disables external comment scanning at both positions inside the quotes.
    char_literal: $ => seq("'", choice($.char_content, $.char_escape_sequence, $._char_boundary),
      choice(token.immediate("'"), $._char_boundary)),
    char_content: $ => token.immediate(/[^'\\\t\r\n]/),
    char_escape_sequence: $ => token.immediate(seq('\\', choice(/["'\\nrt0]/,
      /x[0-7][0-9a-fA-F]/, /u\{[0-9a-fA-F]_*([0-9a-fA-F]_*){0,5}\}/))),
    byte_char_literal: $ => seq("b'", choice($.byte_char_content, $.byte_char_escape_sequence, $._char_boundary),
      choice(token.immediate("'"), $._char_boundary)),
    byte_char_content: $ => token.immediate(/[\x00-\x08\x0b\x0c\x0e-\x26\x28-\x5b\x5d-\x7f]/),
    byte_char_escape_sequence: $ => token.immediate(seq('\\', choice(/["'\\nrt0]/,
      /x[0-9a-fA-F]{2}/))),
    byte_string_literal: $ => seq('b"', repeat(choice($.byte_string_content, $.byte_escape_sequence)),
      choice(alias($._string_end, '"'), $.unterminated_string_end)),
    byte_escape_sequence: $ => token.immediate(seq('\\', choice(/["'\\nrt0]/,
      /x[0-9a-fA-F]{2}/, /\r?\n[ \t\r\n]*/))),
    string_literal: $ => seq('"', repeat(choice($.string_content, $.escape_sequence)),
          choice(alias($._string_end, '"'), $.unterminated_string_end)),
        interpolated_string: $ => seq('"', repeat(choice($.string_content, $.escape_sequence)),
          $.interpolation, repeat(choice($.string_content, $.escape_sequence, $.interpolation)),
      choice(alias($._string_end, '"'), $.unterminated_string_end)),
    escape_sequence: $ => token.immediate(seq('\\', choice(/["'\\nrt0]/,
      /x[0-7][0-9a-fA-F]/, /u\{[0-9a-fA-F]_*([0-9a-fA-F]_*){0,5}\}/,
      /\r?\n[ \t\r\n]*/))),
    // Immediate tokens and the scanner boundary prohibit whitespace/comments in holes.
    interpolation: $ => seq(token.immediate('{'),
      field('name', choice(alias($._hole_name, $.identifier), $._hole_boundary)),
      optional($.interpolation_format), choice(token.immediate('}'), $._hole_boundary)),
    interpolation_format: $ => seq(token.immediate(':'), choice(token.immediate('?'), $._hole_boundary)),
    identifier: $ => /[A-Za-z_][A-Za-z0-9_]*/,
    line_comment: $ => token(seq('//', optional(choice(/[^\/!\r\n][^\r\n]*/, /\/\/[^\r\n]*/)))),
    doc_line_comment: $ => token(choice(seq('///', /[^\/\r\n][^\r\n]*/), '///', seq('//!', /[^\r\n]*/))),
  },
});
